package com.example.data.model

enum class WalnutRegion(val displayName: String, val iconLabel: String) {
    EAST("Island East", "🌴"),
    NORTH("Island North", "🌋"),
    WEST("Island West", "🌾"),
    SOUTH("Island South & Cove", "🏖️"),
    VOLCANO("Volcano Dungeon", "🔥"),
    GENERAL("Island-Wide", "🌊")
}

enum class WalnutCategory(val displayName: String) {
    BUSH("Hidden Bush"),
    BURIED("Buried Treasure"),
    PUZZLE("Island Puzzle"),
    QUEST("Quest / NPC"),
    FIELD_OFFICE("Field Office"),
    FARMING("Island Farming"),
    FISHING("Island Fishing"),
    MINING("Mining / Nodes"),
    COMBAT("Monster Drops")
}

